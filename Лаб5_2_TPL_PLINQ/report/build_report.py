def mr(text, plain=False):
    sty = '<m:rPr><m:sty m:val="p"/></m:rPr>' if plain else ""
    t = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    return f'<m:r>{sty}<w:rPr><w:rFonts w:ascii="Cambria Math" w:hAnsi="Cambria Math"/></w:rPr><m:t xml:space="preserve">{t}</m:t></m:r>'


def msub(base, sub):
    return f"<m:sSub><m:e>{base}</m:e><m:sub>{sub}</m:sub></m:sSub>"


def msup(base, sup):
    return f"<m:sSup><m:e>{base}</m:e><m:sup>{sup}</m:sup></m:sSup>"


def mfrac(num, den):
    return f"<m:f><m:num>{num}</m:num><m:den>{den}</m:den></m:f>"


def mfunc(name, arg):
    return f"<m:func><m:fName>{mr(name, plain=True)}</m:fName><m:e>{arg}</m:e></m:func>"


def mdelim(inner):
    return f"<m:d><m:e>{inner}</m:e></m:d>"


def after_table_space(p):
    global pending_space
    if pending_space:
        p.paragraph_format.space_before = Pt(12)
        pending_space = False


