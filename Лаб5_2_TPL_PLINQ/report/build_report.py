def TABLE(caption, header, rows, widths=None):
    global tab_no, pending_space
    tab_no += 1
    c = doc.add_paragraph()
    c.paragraph_format.first_line_indent = Cm(0)
    c.alignment = WD_ALIGN_PARAGRAPH.LEFT
    c.paragraph_format.space_before = Pt(12)
    c.paragraph_format.keep_with_next = True
    add_runs(c, f"Таблица {tab_no} – {caption}")
    t = doc.add_table(rows=1 + len(rows), cols=len(header))
    t.style = st["Table Grid"]
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    total = Mm(165)
    if widths is None:
        widths = [1] * len(header)
    s = sum(widths)
    col_w = [int(total * w / s) for w in widths]
    for j, w in enumerate(col_w):
        t.columns[j].width = w   # w:gridCol – при fixed-разметке Word берет ширины отсюда
    tblW = t._tbl.tblPr.find(qn("w:tblW"))
    tblW.set(qn("w:w"), str(int(165 / 25.4 * 1440)))
    tblW.set(qn("w:type"), "dxa")
    for i, row in enumerate([header] + rows):
        tr = t.rows[i]
        trPr = tr._tr.get_or_add_trPr()
        trPr.append(parse_xml(f'<w:cantSplit {nsdecls("w")}/>'))
        if i == 0:
            trPr.append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))
        for j, val in enumerate(row):
            cell = tr.cells[j]
            cell.width = col_w[j]
            set_cell(cell, str(val))
            if i < len(rows):
                # строки таблицы держатся вместе с названием, если помещаются
                cell.paragraphs[0].paragraph_format.keep_with_next = True
    pending_space = True
    return tab_no


