LIST_FONT, LIST_LINE = 10, 11.5


def CODE(path, skip=()):
    lines = path.read_text(encoding="utf-8-sig").rstrip("\n").split("\n")
    # компактный листинг: без пустых строк и строк, состоящих только из комментария
    lines = [l for l in lines if l.strip() and not l.strip().startswith("//")]
    if skip:
        kept, cur = [], None
        for l in lines:
            m = re.match(r"namespace (\w+)", l)
            if m:
                cur = m.group(1)
            if cur not in skip:
                kept.append(l)
        lines = kept
        # только вычислительная часть: замеры времени и вывод в консоль опущены
        kept, skipping = [], False
        drop = re.compile(r"^(Console\.Write|sw\.|Stopwatch |var sw |(long )?\w*[Tt]ime\s*=\s*sw\.|(long |int )?\w+ = \(int\)sw\.)")
        for l in lines:
            t = l.strip()
            if not skipping and drop.match(t):
                skipping = True
            if skipping:
                if t.endswith(";"):
                    skipping = False
                continue
            kept.append(l)
        lines = kept
    for line in lines:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.first_line_indent = Cm(0)
        pf.alignment = WD_ALIGN_PARAGRAPH.LEFT
        pf.line_spacing_rule = WD_LINE_SPACING.EXACTLY
        pf.line_spacing = Pt(LIST_LINE)
        r = p.add_run(line.replace("\t", "    ") if line else "")
        r.font.name = "Courier New"
        r._element.rPr.rFonts.set(qn("w:cs"), "Courier New")
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "Courier New")
        r.font.size = Pt(LIST_FONT)


