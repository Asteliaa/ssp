using Xunit;

// Несколько тестовых классов перехватывают Console.Out (общий статический
// ресурс процесса), чтобы проверить текст, который печатают демонстрационные
// методы. При параллельном запуске классов xUnit это приводит к гонкам:
// один тест успевает подменить Console.Out раньше, чем другой прочитает
// свой вывод, и получает пустую строку. Отключаем параллелизацию — набор
// тестов небольшой, потеря скорости незаметна, а результат стабилен.
[assembly: CollectionBehavior(DisableTestParallelization = true)]
